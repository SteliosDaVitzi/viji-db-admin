import assert from 'node:assert/strict'
const base = process.env.WEBDB_URL || 'http://127.0.0.1:34616'
const html = await fetch(base)
assert.equal(html.status, 200)
const setup = await html.text()
assert.match(setup, /Connect to your database/)
assert.match(setup, /Browse all databases in this instance/)
assert.match(setup, /Save connection and credentials/)
const saved = await (await fetch(`${base}/api/connections`)).json()
assert.equal(typeof saved.enabled, 'boolean')
assert.ok(Array.isArray(saved.connections))
for (const item of saved.connections) assert.deepEqual(Object.keys(item).sort(), ['id', 'name'])
assert.equal((await fetch(`${base}/api/databases`)).status, 401)
const body = JSON.stringify({ provider: 'demo', host: '', port: 5432, database: '', username: '', password: '', ssl: true })
const denied = await fetch(`${base}/api/session`, { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://untrusted.example' }, body })
assert.equal(denied.status, 403)
const connected = await fetch(`${base}/api/session`, { method: 'POST', headers: { 'content-type': 'application/json', origin: base }, body })
assert.equal(connected.status, 200)
const cookie = connected.headers.get('set-cookie')?.split(';')[0]
assert.ok(cookie)
const headers = { cookie }
const session = await (await fetch(`${base}/api/session`, { headers })).json()
assert.equal(session.database, 'sample_workspace')
assert.ok(!('password' in session))
assert.equal(session.allDatabases, false)
const deniedSwitch = await fetch(`${base}/api/databases`, { method: 'POST', headers: { ...headers, 'content-type': 'application/json', origin: base }, body: JSON.stringify({ database: 'other' }) })
assert.equal(deniedSwitch.status, 400)
assert.equal((await fetch(`${base}/api/tables?database=outside-session`, { headers })).status, 400)
const tables = await (await fetch(`${base}/api/tables`, { headers })).json()
assert.equal(tables.length, 3)
const rows = await (await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=25&sort=id&descending=true`, { headers })).json()
assert.equal(rows.rows.length, 25)
assert.equal(rows.rows[0].id, '124')
assert.equal(rows.columns[0].primaryKey, true)
assert.equal(rows.hasMore, true)
const last = await (await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=25&page=4`, { headers })).json()
assert.equal(last.rows.length, 24)
assert.equal(last.hasMore, false)
assert.equal((await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=1000`, { headers })).status, 200)
assert.equal((await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=1001`, { headers })).status, 400)
const queryBody = JSON.stringify({ sql: 'SELECT * FROM "public"."orders" LIMIT 7;', pageSize: 5, page: 1 })
const queryDenied = await fetch(`${base}/api/query`, { method: 'POST', headers: { ...headers, 'content-type': 'application/json', origin: 'https://untrusted.example' }, body: queryBody })
assert.equal(queryDenied.status, 403)
const queryResponse = await fetch(`${base}/api/query`, { method: 'POST', headers: { ...headers, 'content-type': 'application/json', origin: base }, body: queryBody })
assert.equal(queryResponse.status, 200)
const query = await queryResponse.json()
assert.equal(query.rows.length, 2)
assert.equal(query.rows[0].id, '6')
assert.equal(query.hasMore, false)
const writeDenied = await fetch(`${base}/api/query`, { method: 'POST', headers: { ...headers, 'content-type': 'application/json', origin: base }, body: JSON.stringify({ sql: 'DELETE FROM orders' }) })
assert.equal(writeDenied.status, 400)
const mutationBody = JSON.stringify({ confirmation: 'APPLY', mutation: { action: 'dropTable', schema: 'public', table: 'customers' } })
assert.equal((await fetch(`${base}/api/mutations`, { method: 'POST', headers: { ...headers, 'content-type': 'application/json', origin: 'https://untrusted.example' }, body: mutationBody })).status, 403)
assert.equal((await fetch(`${base}/api/mutations`, { method: 'POST', headers: { ...headers, 'content-type': 'application/json', origin: base }, body: mutationBody })).status, 400)
assert.equal((await fetch(`${base}/api/session`, { method: 'DELETE', headers: { ...headers, origin: base } })).status, 204)
assert.equal((await fetch(`${base}/api/tables`, { headers })).status, 401)
console.log('Smoke checks passed: SSR, origin protection, proxy, cookies, session restore, tables, sorting, pagination, read-only queries, validation, disconnect.')
