import assert from 'node:assert/strict'
const base = process.env.WEBDB_URL || 'http://127.0.0.1:34616'
const html = await fetch(base)
assert.equal(html.status, 200)
assert.match(await html.text(), /Connect to your database/)
const body = JSON.stringify({ provider: 'demo', host: '', port: 5432, database: '', username: '', password: '', ssl: true })
const denied = await fetch(`${base}/api/session`, { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://untrusted.example' }, body })
assert.equal(denied.status, 403)
const connected = await fetch(`${base}/api/session`, { method: 'POST', headers: { 'content-type': 'application/json', origin: base }, body })
assert.equal(connected.status, 200)
const cookie = connected.headers.get('set-cookie')?.split(';')[0]
assert.ok(cookie)
const headers = { cookie }
const session = await (await fetch(`${base}/api/session`, { headers })).json()
assert.equal(session.database, 'sample_workspace')
assert.ok(!('password' in session))
const tables = await (await fetch(`${base}/api/tables`, { headers })).json()
assert.equal(tables.length, 3)
const rows = await (await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=25&sort=id&descending=true`, { headers })).json()
assert.equal(rows.rows.length, 25)
assert.equal(rows.rows[0].id, '124')
assert.equal(rows.columns[0].primaryKey, true)
assert.equal(rows.hasMore, true)
const last = await (await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=25&page=4`, { headers })).json()
assert.equal(last.rows.length, 24)
assert.equal(last.hasMore, false)
assert.equal((await fetch(`${base}/api/rows?schema=public&table=customers&pageSize=1000`, { headers })).status, 400)
assert.equal((await fetch(`${base}/api/session`, { method: 'DELETE', headers: { ...headers, origin: base } })).status, 204)
assert.equal((await fetch(`${base}/api/tables`, { headers })).status, 401)
console.log('Smoke checks passed: SSR, origin protection, proxy, cookies, session restore, tables, sorting, pagination, validation, disconnect.')
